// Compiles the harness contracts with solc and vendors the ABIs + bytecode
// into src/local-node/artifacts.ts (checked in, so running this is only
// needed after editing the .sol sources).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const sources = {
  'contracts/LocalTestToken.sol': readFileSync(
    resolve(root, 'contracts/LocalTestToken.sol'),
    'utf8',
  ),
  'contracts/LocalCasinoHost.sol': readFileSync(
    resolve(root, 'contracts/LocalCasinoHost.sol'),
    'utf8',
  ),
  // Mirrors of the production session struct + codec the host commits and echoes.
  'contracts/casino/CasinoSession.sol': readFileSync(
    resolve(root, 'contracts/casino/CasinoSession.sol'),
    'utf8',
  ),
  'contracts/casino/CasinoSessionCodec.sol': readFileSync(
    resolve(root, 'contracts/casino/CasinoSessionCodec.sol'),
    'utf8',
  ),
};

function findImports(importPath) {
  try {
    return { contents: readFileSync(resolve(root, importPath), 'utf8') };
  } catch {
    return { error: `Import not found: ${importPath}` };
  }
}

const input = {
  language: 'Solidity',
  sources: Object.fromEntries(
    Object.entries(sources).map(([path, content]) => [path, { content }]),
  ),
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));

const errors = (output.errors ?? []).filter(error => error.severity === 'error');
if (errors.length > 0) {
  for (const error of errors) console.error(error.formattedMessage);
  process.exit(1);
}
for (const warning of (output.errors ?? []).filter(error => error.severity === 'warning')) {
  console.warn(warning.formattedMessage);
}

function artifact(file, name) {
  const contract = output.contracts[file]?.[name];
  if (!contract) throw new Error(`Missing compiled contract ${name} in ${file}`);
  return { abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}` };
}

const contracts = {
  localTestToken: artifact('contracts/LocalTestToken.sol', 'LocalTestToken'),
  localCasinoHost: artifact('contracts/LocalCasinoHost.sol', 'LocalCasinoHost'),
  localCasinoVault: artifact('contracts/LocalCasinoHost.sol', 'LocalCasinoVault'),
};

const banner = `// Generated by scripts/compile-contracts.mjs from contracts/*.sol — do not edit by hand.
import type { Hex } from 'viem';
`;

const body = Object.entries(contracts)
  .map(
    ([key, { abi, bytecode }]) =>
      `export const ${key}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
      `export const ${key}Bytecode: Hex = '${bytecode}';\n`,
  )
  .join('\n');

const outPath = resolve(root, 'src/local-node/artifacts.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${banner}\n${body}`);
console.log(`Wrote ${outPath}`);
console.log('Run your formatter over the generated file if your tooling checks formatting.');
